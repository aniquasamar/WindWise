#!/usr/bin/env python3
"""Generate frontend/src/api/types.ts from backend/app/api/schemas.py.

The schema file is read as text (no pydantic or FastAPI needed), so this runs anywhere.

  python scripts/gen_ts_types.py           write the file
  python scripts/gen_ts_types.py --check   exit 1 if the committed file is out of date
"""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "backend" / "app" / "api" / "schemas.py"
TARGET = ROOT / "frontend" / "src" / "api" / "types.ts"

PRIMITIVES = {"str": "string", "int": "number", "float": "number", "bool": "boolean", "date": "string"}
HEADER = """// GENERATED by scripts/gen_ts_types.py from backend/app/api/schemas.py. Do not edit by hand.
// Dates are ISO strings (YYYY-MM-DD); timestamps are ISO 8601 UTC strings ending in Z.
"""


def ts_type(node: ast.expr) -> str:
    if isinstance(node, ast.Name):
        return PRIMITIVES.get(node.id, node.id)
    if isinstance(node, ast.Subscript) and isinstance(node.value, ast.Name):
        inner = ts_type(node.slice)
        if node.value.id == "Optional":
            return f"{inner} | null"
        if node.value.id == "list":
            return f"({inner})[]" if "|" in inner else f"{inner}[]"
    raise ValueError(f"unsupported annotation: {ast.dump(node)}")


def generate() -> str:
    tree = ast.parse(SOURCE.read_text(encoding="utf-8"))
    blocks = []
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        lines = [f"export interface {node.name} {{"]
        for stmt in node.body:
            if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                lines.append(f"  {stmt.target.id}: {ts_type(stmt.annotation)};")
        lines.append("}")
        blocks.append("\n".join(lines))
    return HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> int:
    content = generate()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current.rstrip() != content.rstrip():     # a missing final newline is harmless
            print(f"{TARGET} is out of date. Run: python scripts/gen_ts_types.py")
            return 1
        print("types.ts is up to date")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())